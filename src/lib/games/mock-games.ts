function toSummary(g: MockGameItem): MediaSummary {
  return {
    type: "game",
    id: g.id,
    title: g.title,
    originalTitle: null,
    posterPath: g.image,
    backdropPath: g.image,
    date: g.date,
    year: g.year,
    genres: g.genres,
    overview: g.overview,
    score: g.score,
    voteCount: 1500,
    popularity: g.score * 10,
    originalLanguage: "en",
  };
}

export const mockGames = {
  getTrending(page = 1): Paged<MediaSummary> {
    const list = [...MOCK_GAMES].sort((a, b) => b.score - a.score);
    return {
      page,
      totalPages: 1,
      totalResults: list.length,
      results: list.map(toSummary),
    };
  },
  getTopRated(page = 1): Paged<MediaSummary> {
    const list = [...MOCK_GAMES].sort((a, b) => b.score - a.score);
    return {
      page,
      totalPages: 1,
      totalResults: list.length,
      results: list.map(toSummary),
    };
  },
  getNew(page = 1): Paged<MediaSummary> {
    const list = [...MOCK_GAMES].sort((a, b) => b.date.localeCompare(a.date));
    return {
      page,
      totalPages: 1,
      totalResults: list.length,
      results: list.map(toSummary),
    };
  },
  search(query: string, page = 1): Paged<MediaSummary> {
    const q = query.toLowerCase().trim();
    const list = MOCK_GAMES.filter(
      (g) => g.title.toLowerCase().includes(q) || g.genres.some((gen) => gen.toLowerCase().includes(q)),
    );
    return {
      page,
      totalPages: 1,
      totalResults: list.length,
      results: list.map(toSummary),
    };
  },
  getDetails(id: number): MediaDetails | null {
    const g = MOCK_GAMES.find((game) => game.id === id);
    if (!g) return null;
    const summary = toSummary(g);
    return {
      ...summary,
      tagline: g.platforms.slice(0, 4).join(" · "),
      format: "Video Game",
      status: "Released",
      rawStatus: "Released",
      endDate: null,
      runtime: g.playtime * 60,
      episodes: 1,
      seasons: null,
      seasonList: [],
      studios: [g.developer, g.publisher],
      networks: [],
      countries: [],
      languages: ["English"],
      certification: null,
      budget: null,
      revenue: null,
      homepage: null,
      nextEpisode: null,
      lastEpisode: null,
      creators: [],
      cast: [],
      crew: [],
      videos: [],
      trailer: null,
      recommendations: MOCK_GAMES.filter((o) => o.id !== g.id).slice(0, 6).map(toSummary),
      similar: [],
      collection: null,
      keywords: g.genres,
      platforms: g.platforms,
      developers: [g.developer],
      publishers: [g.publisher],
      externalIds: { imdb: null, tvdb: null, wikidata: null, instagram: null, twitter: null, facebook: null },
      watch: null,
    };
  },
};
